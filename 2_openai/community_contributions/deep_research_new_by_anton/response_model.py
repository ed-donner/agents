from __future__ import annotations

from pydantic import BaseModel, Field


class WebSearchItem(BaseModel):
    reason: str = Field(
        description="Your reasoning for why this search is important to the query."
    )
    query: str = Field(description="The search term to use for the web search.")


class WebSearchPlan(BaseModel):
    searches: list[WebSearchItem] = Field(
        description="A list of web searches to perform to best answer the query."
    )


class ReportData(BaseModel):
    short_summary: str = Field(
        description="A short 2-3 sentence summary of the findings."
    )
    markdown_report: str = Field(description="The final report")
    follow_up_questions: list[str] = Field(
        description="Suggested topics to research further"
    )


class ResearchAgentResponse(BaseModel):
    query: str = Field(description="The user query to research.")
    web_search_plan: WebSearchPlan = Field(
        description="The plan of web searches to perform to gather information about the query's topic."
    )
    report: ReportData = Field(
        description="The final report generated by the research agent."
    )
    report_email_confirmation: bool = Field(
        description="Confirmation that the report email was sent successfully."
    )
