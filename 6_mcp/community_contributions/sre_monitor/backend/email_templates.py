def markdown_to_email_html(markdown: str) -> str:
    """Render trusted report Markdown and add inline styles for email clients."""
    markdown = re.sub(
        r"(?m)^Link:\s+(https?://\S+)\s*$",
        r"**Incident link:** [View vendor incident](\1)",
        markdown,
    )
    try:
        from markdown_it import MarkdownIt

        rendered = MarkdownIt(
            "commonmark", {"html": False, "linkify": False, "typographer": False}
        ).enable("table").render(markdown)
    except Exception:
        return (
            '<pre style="white-space:pre-wrap;font:13px/1.55 Menlo,Consolas,monospace;'
            f'color:#334155">{escape(markdown)}</pre>'
        )

    soup = BeautifulSoup(rendered, "html.parser")
    styles = {
        "h1": "font-family:Arial,sans-serif;font-size:24px;line-height:1.3;color:#0f172a;margin:0 0 18px",
        "h2": "font-family:Arial,sans-serif;font-size:19px;line-height:1.35;color:#0f172a;margin:28px 0 10px;padding-bottom:7px;border-bottom:2px solid #dbeafe",
        "h3": "font-family:Arial,sans-serif;font-size:16px;line-height:1.4;color:#1e3a5f;margin:22px 0 8px",
        "p": "font-family:Arial,sans-serif;font-size:14px;line-height:1.6;color:#334155;margin:8px 0 13px",
        "ul": "font-family:Arial,sans-serif;font-size:14px;line-height:1.55;color:#334155;margin:8px 0 16px;padding-left:22px",
        "ol": "font-family:Arial,sans-serif;font-size:14px;line-height:1.55;color:#334155;margin:8px 0 16px;padding-left:22px",
        "li": "margin:5px 0",
        "table": "width:100%;border-collapse:collapse;margin:12px 0 22px;font-family:Arial,sans-serif;font-size:12px",
        "th": "background:#eaf2ff;color:#1e3a5f;font-weight:bold;text-align:left;padding:9px;border:1px solid #cbd5e1",
        "td": "color:#334155;text-align:left;vertical-align:top;padding:9px;border:1px solid #dbe3ee",
        "a": "color:#155eef;text-decoration:underline",
        "code": "font-family:Menlo,Consolas,monospace;font-size:12px;background:#f1f5f9;color:#0f172a;padding:2px 4px;border-radius:3px",
        "blockquote": "margin:12px 0;padding:8px 14px;border-left:4px solid #94a3b8;background:#f8fafc;color:#475569",
        "hr": "border:0;border-top:1px solid #e2e8f0;margin:22px 0",
    }
    for tag_name, style in styles.items():
        for tag in soup.find_all(tag_name):
            tag["style"] = style
            if tag_name == "a":
                tag["target"] = "_blank"
                tag["rel"] = "noopener"
    return str(soup)
